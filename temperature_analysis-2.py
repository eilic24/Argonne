"""## Data Sources
### Load data from Glen Canyon Dam
"""

df_reports = pl.read_parquet(
    PATH_DATA / "glen_canyon_dam.parquet"
).with_columns(
    pl.col("timestamp").dt.convert_time_zone("MST").dt.replace_time_zone(None).cast(pl.Datetime("ms"))
).rename({
    "gc_turbine_temp": "T_turbine_C",
    "gc_bypass_temp": "T_bypass_C",
    "gc_bypass_release_cfs": "Q_bypass_cfs",
    "gc_turbine_release_cfs": "Q_turbine_cfs",
    "gc_bypass_volume_cf": "V_bypass_cf",
    "gc_turbine_volume_cf": "V_turbine_cf"
})

df_reports

"""### Load data from GCMRC"""

df_gcmrc_lcr = pl.read_csv(
    PATH_DATA / "gcmrc_lcr.tsv",
    separator="\t",
).select(
    pl.col("Water Temperature(°C)-09383100").alias("T_lcr_C"),
    pl.col("Discharge(cfs)-09383100").alias("Q_lcr_cfs"),
    pl.col("Gage Height(ft)-09383100").alias("h_lcr_ft"),
    pl.col("time (MST)").str.strptime(pl.Datetime("ms"), "%Y-%m-%d %H:%M:%S").alias("date")
).with_columns(
    (pl.col("Q_lcr_cfs") / AFH_TO_CFS).alias("V_lcr")
).group_by_dynamic(
    "date",
    every="1h",
).agg(
    pl.col("T_lcr_C").mean(),
    pl.col("Q_lcr_cfs").mean(),
    pl.col("h_lcr_ft").mean(),
    pl.col("V_lcr").sum(),
).sort("date")

df_gcmrc_lf = pl.read_csv(
    PATH_DATA / "gcmrc_lf.tsv",
    separator="\t",
).select(
    pl.col("Water Temperature(°C)-09380000").alias("T_lf_C"),
    pl.col("Gage Height(ft)-09380000").alias("h_lf_ft"),
    pl.col("time (MST)").str.strptime(pl.Datetime("ms"), "%Y-%m-%d %H:%M:%S").alias("date")
).group_by_dynamic(
    "date",
    every="1h",
).agg(
    pl.col("T_lf_C").mean(),
    pl.col("h_lf_ft").mean()
).sort("date")

df_gcmrc_gc = pl.read_csv(
    PATH_DATA / "gcmrc_gc.tsv",
    separator="\t",
).select(
    pl.col("Water Temperature(°C)-09379901").alias("T_gc_C"),
    pl.col("time (MST)").str.strptime(pl.Datetime("ms"), "%Y-%m-%d %H:%M:%S").alias("date")
).group_by_dynamic(
    "date",
    every="1h",
).agg(
    pl.col("T_gc_C").mean(),
).sort("date")

df_gcmrc = df_gcmrc_lcr.join(
    df_gcmrc_lf, on="date", how="inner"
).join(
    df_gcmrc_gc, on="date", how="inner"
).rename({
    "date": "timestamp"
})

df_gcmrc

